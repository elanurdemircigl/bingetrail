#!/usr/bin/env node
// Copies shared wire contracts into the Edge Functions tree (Deno cannot import
// workspace packages). `--check` fails instead of writing, for CI.
//
// Usage: node tooling/scripts/sync-contracts.mjs [--check]
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const FILES = ['catalog.ts', 'account.ts'];
const SOURCE_DIR = join(ROOT, 'packages', 'shared', 'src', 'contracts');
const TARGET_DIR = join(ROOT, 'supabase', 'functions', '_shared', 'contracts');
const HEADER =
  '// GENERATED by tooling/scripts/sync-contracts.mjs — DO NOT EDIT.\n' +
  '// Source: packages/shared/src/contracts/. Run `pnpm contracts:sync` after changing it.\n';

const check = process.argv.includes('--check');
let drift = 0;

for (const file of FILES) {
  const expected = HEADER + readFileSync(join(SOURCE_DIR, file), 'utf8').replace(/\r\n/g, '\n');
  const target = join(TARGET_DIR, file);
  const actual = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;

  if (actual === expected) continue;
  if (check) {
    console.error(`✖ ${file} is out of date. Run \`pnpm contracts:sync\`.`);
    drift++;
  } else {
    mkdirSync(TARGET_DIR, { recursive: true });
    writeFileSync(target, expected);
    console.log(`synced ${file}`);
  }
}

if (drift) process.exit(1);
if (check) console.log('contracts: in sync');
